local set = vim.api.nvim_set_hl

local function hl(name, fg, bg, attr, sp)
	local s = attr and vim.deepcopy(attr) or {}
	s.fg, s.bg, s.sp = fg, bg, sp
	set(0, name, s)
end

local function link(name, to) set(0, name, { link = to }) end

