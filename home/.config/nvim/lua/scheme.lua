local function plugins(p)
	hl('MiniStatuslineModeNormal', p.bg, p.mode.normal)
	hl('MiniStatuslineModeInsert', p.bg, p.mode.insert)
	hl('MiniStatuslineModeVisual', p.bg, p.mode.visual)
	hl('MiniStatuslineModeReplace', p.bg, p.mode.replace)
	hl('MiniStatuslineModeCommand', p.bg, p.mode.command)
	hl('MiniStatuslineModeOther', p.bg, p.mode.other)
	hl('MiniStatuslineDevinfo', p.fg, p.raised)
	hl('MiniStatuslineFileinfo', p.fg, p.raised)
	link('MiniStatuslineFilename', 'StatusLine')
	link('MiniStatuslineInactive', 'StatusLineNC')
	hl('GitSignsDiffStaged', p.faint)
	for ty, col in pairs { Add = p.staged_add, Untracked = p.staged_add, Change = p.staged_change, Changedelete = p.staged_change, Delete = p.staged_delete, Topdelete = p.staged_delete } do
		for _, kind in ipairs { '', 'Nr', 'Cul', 'Ln' } do
			hl('GitSignsStaged' .. ty .. kind, col)
		end
	end
	link('BlinkCmpLabelMatch', 'PmenuMatch')
	link('TelescopeMatching', 'PmenuMatch')
	link('TelescopePromptPrefix', 'Directory')
	link('TelescopeSelection', 'PmenuSel')
end

return function(name, p)
	vim.cmd.highlight 'clear'
	if vim.g.syntax_on then vim.cmd.syntax 'reset' end
	vim.o.background = 'dark'
	vim.g.colors_name = name

	for i = 0, 15 do
		vim.g['terminal_color_' .. i] = p.ansi[i + 1]
	end

	ui(p)
	syntax(p)
	lsp(p)
	plugins(p)
end
